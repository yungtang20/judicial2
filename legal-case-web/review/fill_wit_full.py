wb = openpyxl.load_workbook(
    r"D:\工作用\judicial1\新套表.xlsm", keep_vba=True, data_only=False)
ws = wb["證人筆錄"]
headers = [c.value for c in ws[1]]
for h in W:
    if h == "偽造文書_dup":
        continue
    if h not in headers:
        headers.append(h)
        c = ws.cell(row=1, column=len(headers), value=h)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill(start_color="4F81BD", end_color="4F81BD", fill_type="solid")
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        from openpyxl.utils import get_column_letter
        ws.column_dimensions[get_column_letter(len(headers))].width = 55
start_row = ws.max_row + 1
for j, h in enumerate(headers, 1):
    for k, q in enumerate(W.get(h, [])):
        if h == "偽造文書_dup":
            continue
        c = ws.cell(row=start_row + k, column=j, value=q)
        c.alignment = Alignment(vertical="center", wrap_text=True)
n = sum(len(v) for v in W.values())
print(f"WIT_FILL cols={len([k for k in W if k!='偽造文書_dup'])} Qs={n}")
