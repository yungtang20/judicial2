wb = openpyxl.load_workbook(
    r"D:\工作用\judicial1\新套表.xlsm", keep_vba=True, data_only=False)
ws = wb["被害人筆錄"]
headers = [c.value for c in ws[1]]
for h in V:
    if h not in headers:
        headers.append(h)
        c = ws.cell(row=1, column=len(headers), value=h)
        c.font = openpyxl.styles.Font(bold=True, color="FFFFFF")
        c.fill = openpyxl.styles.PatternFill(start_color="4F81BD", end_color="4F81BD", fill_type="solid")
        c.alignment = openpyxl.styles.Alignment(horizontal="center", vertical="center", wrap_text=True)
        from openpyxl.utils import get_column_letter
        ws.column_dimensions[get_column_letter(len(headers))].width = 55
start_row = ws.max_row + 1
for j, h in enumerate(headers, 1):
    for k, q in enumerate(V.get(h, [])):
        c = ws.cell(row=start_row + k, column=j, value=q)
        c.alignment = openpyxl.styles.Alignment(vertical="center", wrap_text=True)
n = sum(len(v) for v in V.values())
